"""The output commitment a worker signs, exactly as Grid Core computes it.

Core owns this contract (`grid_api/services/chat_output.py::result_hash`,
`ledger.py::content_hash`/`canonical_hash`, `signing.py::signed_message`). Core
rebuilds the hash from the stream it witnessed and stores the worker signature
only if it verifies over that hash, so any drift here silently records every
job as unsigned. `tests/test_result_commitment.py` pins vectors generated by
Core's own functions; change both sides together.
"""

import hashlib
import json

SIGNING_DOMAIN = "aipg-job"
_RICH_SCHEMA = "aipg.chat-output.v2"


def merge_tool_call_deltas(acc: dict, deltas: list | None) -> None:
    """Join streamed function-call fragments by index, as Core does."""
    for tc in deltas or []:
        idx = tc.get("index", 0)
        slot = acc.setdefault(
            idx,
            {"index": idx, "id": None, "type": "function", "function": {"name": "", "arguments": ""}},
        )
        if tc.get("id"):
            slot["id"] = tc["id"]
        if tc.get("type"):
            slot["type"] = tc["type"]
        fn = tc.get("function") or {}
        if fn.get("name"):
            slot["function"]["name"] += fn["name"]
        if fn.get("arguments"):
            slot["function"]["arguments"] += fn["arguments"]


def merged_tool_calls(acc: dict) -> list | None:
    return [acc[i] for i in sorted(acc)] if acc else None


def result_hash(content: str, reasoning: str = "", tool_calls: list | None = None) -> str | None:
    """sha256 commitment over the result, or None when there is nothing to commit to.

    Visible text alone is hashed directly. Reasoning or tool calls switch to a
    canonical JSON envelope, so a signature over visible text can never
    authenticate a richer result.
    """
    if not reasoning and not tool_calls:
        return hashlib.sha256(content.encode()).hexdigest() if content else None
    envelope = {
        "schema": _RICH_SCHEMA,
        "content": content,
        "reasoning_content": reasoning,
        "tool_calls": tool_calls or [],
    }
    data = json.dumps(envelope, sort_keys=True, separators=(",", ":"), default=str)
    return hashlib.sha256(data.encode()).hexdigest()


def signed_message(job_id: str, commitment: str) -> str:
    return f"{SIGNING_DOMAIN}:{job_id}:{commitment}"
