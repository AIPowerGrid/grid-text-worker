"""The worker's result signature must verify under Grid Core's contract.

Expected hashes were generated by Core's own `chat_output.result_hash`,
`merge_tool_call_deltas` and `signing.signed_message` at grid-core
`81305f89`. Mock backend and socket only; not a live Core settlement.
"""

import asyncio
import json
from types import SimpleNamespace

import httpx
import pytest
from eth_account import Account
from eth_account.messages import encode_defunct

from inference_worker import result_commitment, ws_client
from inference_worker.config import Settings

TOOL_FRAGMENTS = [
    [{"index": 0, "id": "call_1", "type": "function",
      "function": {"name": "get_", "arguments": "{\"ci"}}],
    [{"index": 0, "function": {"name": "weather", "arguments": "ty\":\"Zürich\"}"}},
     {"index": 1, "id": "call_2", "function": {"name": "now", "arguments": "{}"}}],
]
CORE_ALL_HASH = "8c049da71885d3b5eb79819ee5fffcde20fe5ec56fd33a28e2ece8f8a68a7402"


def _merged():
    acc = {}
    for fragment in TOOL_FRAGMENTS:
        result_commitment.merge_tool_call_deltas(acc, fragment)
    return result_commitment.merged_tool_calls(acc)


@pytest.mark.parametrize(
    ("content", "reasoning", "tools", "expected"),
    [
        ("Hello, Grid ✓", "", False, "cdb0174866cae98ee36ba5977154ee8a8c0872cb2fd8e4041fbe98103b4ecbbf"),
        ("", "", False, None),
        ("42", "Let me think… 6×7", False, "b33549928152ad677c4ce096b287d44cdc133a506c9dd903bdf2102ce519adc5"),
        ("", "only thoughts", False, "afc1c9380195be42615546384d125b0fa3b748134b4db72988b4ff40800a5a4b"),
        ("", "", True, "0baa1058c75da7b3f03b2816b4a275f4138fe4b0c019d67f336aeda05085f815"),
        ("ok", "r", True, CORE_ALL_HASH),
    ],
)
def test_result_hash_matches_core_vectors(content, reasoning, tools, expected):
    assert result_commitment.result_hash(content, reasoning, _merged() if tools else None) == expected


def test_tool_calls_merge_like_core():
    assert _merged() == [
        {"index": 0, "id": "call_1", "type": "function",
         "function": {"name": "get_weather", "arguments": "{\"city\":\"Zürich\"}"}},
        {"index": 1, "id": "call_2", "type": "function",
         "function": {"name": "now", "arguments": "{}"}},
    ]
    assert result_commitment.merged_tool_calls({}) is None


def test_signed_message_uses_core_domain():
    plain = result_commitment.result_hash("Hello, Grid ✓")
    assert result_commitment.signed_message("job-1", plain) == (
        "aipg-job:job-1:cdb0174866cae98ee36ba5977154ee8a8c0872cb2fd8e4041fbe98103b4ecbbf"
    )


class _Socket:
    """Queue-backed socket: `recv` blocks until Core would have replied."""

    def __init__(self):
        self.queue = asyncio.Queue()
        self.sent = []

    async def recv(self):
        return json.dumps(await self.queue.get())

    async def send(self, raw):
        message = json.loads(raw)
        self.sent.append(message)
        if message["type"] == "done":
            self.queue.put_nowait({"type": "ack", "id": message["id"], "den": 0})


@pytest.mark.asyncio
async def test_streamed_job_sends_signature_core_would_accept(monkeypatch):
    signer = Account.create()
    monkeypatch.setattr(Settings, "validate", lambda: None)
    monkeypatch.setattr(ws_client, "get_signer", lambda: signer)
    worker = ws_client.StreamingWorker(spec=SimpleNamespace(
        name="fixture", model_name="fixture", grid_model_name="fixture",
        modalities=["text"], modalities_declared=True, backend_type="openai",
        url="http://127.0.0.1:8000/v1", api_key="", concurrency=1, schedule="",
    ))
    worker.ws = _Socket()
    deltas = [
        {"role": "assistant"},
        {"reasoning": "r"},  # vLLM's field name; normalized to reasoning_content
        {"tool_calls": TOOL_FRAGMENTS[0]},
        {"content": "o"},
        {"tool_calls": TOOL_FRAGMENTS[1]},
        {"content": "k"},
    ]
    body = "".join(
        "data: " + json.dumps({"choices": [{"delta": delta, "finish_reason": None}]}) + "\n\n"
        for delta in deltas
    ) + "data: [DONE]\n\n"
    await worker.backend.aclose()
    worker.backend = httpx.AsyncClient(
        transport=httpx.MockTransport(lambda request: httpx.Response(200, content=body))
    )
    try:
        await asyncio.wait_for(worker._handle_job({"type": "job", "id": "job-7", "payload": {
            "api_format": "openai-chat",
            "request": {"messages": [{"role": "user", "content": "x"}], "stream": True, "max_tokens": 8},
        }}), 5)
    finally:
        await worker.backend.aclose()

    done = worker.ws.sent[-1]
    assert done["type"] == "done" and "receipt" not in done

    # Rebuild the commitment the way Core does: from the token frames it received.
    content = reasoning = ""
    acc = {}
    for frame in worker.ws.sent:
        if frame["type"] != "token":
            continue
        delta = frame["delta"]
        content += delta.get("content") or ""
        reasoning += delta.get("reasoning_content") or ""
        result_commitment.merge_tool_call_deltas(acc, delta.get("tool_calls"))
    witnessed = result_commitment.result_hash(content, reasoning, result_commitment.merged_tool_calls(acc))
    assert witnessed == CORE_ALL_HASH

    recovered = Account.recover_message(
        encode_defunct(text=f"aipg-job:job-7:{CORE_ALL_HASH}"), signature=done["worker_sig"]
    )
    assert recovered == signer.address


def test_no_signature_without_signer_or_output(monkeypatch):
    monkeypatch.setattr(Settings, "validate", lambda: None)
    monkeypatch.setattr(ws_client, "get_signer", lambda: None)
    spec = SimpleNamespace(
        name="fixture", model_name="fixture", grid_model_name="fixture",
        modalities=["text"], modalities_declared=True, backend_type="openai",
        url="http://127.0.0.1:8000/v1", api_key="", concurrency=1, schedule="",
    )
    unsigned = ws_client.StreamingWorker(spec=spec)
    assert unsigned._sign_receipt("job-1", "text") is None
    monkeypatch.setattr(ws_client, "get_signer", Account.create)
    assert ws_client.StreamingWorker(spec=spec)._sign_receipt("job-1", "") is None
